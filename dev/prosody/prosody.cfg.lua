-- Disposable Prosody for local development. NOT a production config.
--
-- Everything lives under dev/prosody/ so this never touches /etc/prosody or
-- /var/lib/prosody, needs no root, and can be deleted with `rm -rf dev/prosody/data`.
--
-- Start:  prosody --config dev/prosody/prosody.cfg.lua
-- Users:  prosodyctl --config dev/prosody/prosody.cfg.lua register alice localhost secret
--
-- The insecure settings below are deliberate and confined to this file: plaintext auth
-- and optional TLS mean no certificate wrangling to exercise a bridge over loopback.
-- Nothing here should be copied to the droplet.

data_path = "__ROOT__/dev/prosody/data"
pidfile = "__ROOT__/dev/prosody/prosody.pid"

admins = { "admin@localhost" }

modules_enabled = {
	"roster";
	"saslauth";
	"tls";
	"disco";
	"carbons";
	"pep";
	"private";
	"blocklist";
	"vcard4";
	"vcard_legacy";
	"version";
	"uptime";
	"time";
	"ping";
	"register";
	"admin_adhoc";
}

-- Dev only. On the droplet, registration is closed and accounts are made with prosodyctl.
allow_registration = true

-- A real self-signed cert covering localhost, conference.localhost, telegram.localhost
-- and signal.localhost, generated by dev/make-certs.sh. Using a genuine cert rather than
-- turning encryption off matters: slixmpp validates the chain itself and, when
-- validation fails, leaves the stream in a state where authentication silently never
-- happens. Clients trust this cert explicitly via ca_certs, so the dev path exercises
-- the same STARTTLS code as production.
ssl = {
	certificate = "__ROOT__/dev/prosody/certs/localhost.crt";
	key = "__ROOT__/dev/prosody/certs/localhost.key";
}

c2s_require_encryption = true
s2s_require_encryption = true

-- internal_hashed is the sane default; plain keeps dev passwords greppable when
-- debugging auth failures, which is the whole point of a throwaway server.
authentication = "internal_plain"
storage = "internal"

-- Federation off: this server talks to nothing but itself.
modules_disabled = { "s2s" }

log = {
	{ levels = { min = "info" }, to = "console" };
}

VirtualHost "localhost"

-- Where the humans talk. The Zulip bridge joins this room, and so does a test client
-- standing in for an XMPP user.
Component "conference.localhost" "muc"
	modules_enabled = { "muc_mam" }
	restrict_room_creation = false
	-- XEP-0045 says a newly created room stays *locked* until its owner submits a
	-- configuration form. The symptom is nasty: the client that creates the room joins
	-- fine, and every subsequent join hangs forever with no error. Unlocking on creation
	-- means a bridge can just join a room and start working.
	muc_room_locking = false
	muc_tombstones = false

-- Slidge gateways connect as external XEP-0114 components. Telegram and Signal are
-- separate daemons, so each gets its own component domain.
Component "telegram.localhost"
	component_secret = "devsecret"

Component "signal.localhost"
	component_secret = "devsecret"
